import fs from 'node:fs';
// Run from the repo: node scripts/gen-electrical-stencils.mjs [dir-with-downloaded-xml]
// Without a directory, the stencil sets are downloaded from diagrams.net.
const root = new URL('..', import.meta.url).pathname;
const local = process.argv[2];
const groups = [
  'abstract', 'capacitors', 'diodes', 'electro-mechanical', 'iec_logic_gates', 'inductors', 'instruments', 'logic_gates',
  'miscellaneous', 'mosfets1', 'mosfets2', 'opto_electronics', 'plc_ladder', 'radio', 'resistors', 'rot_mech',
  'signal_sources', 'thermionic_devices', 'transistors', 'transmission', 'waveforms',
];

async function read(group) {
  if (local) return fs.readFileSync(`${local}/${group}.xml`, 'utf8');
  const res = await fetch(`https://app.diagrams.net/stencils/electrical/${group}.xml`);
  if (!res.ok) throw new Error(`${group}: HTTP ${res.status}`);
  return res.text();
}

const minify = (xml) =>
  xml
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/>\s+</g, '><')
    .replace(/\s+/g, ' ')
    .trim();

const sets = [];
for (const g of groups) {
  const xml = minify(await read(g));
  if (!xml.startsWith(`<shapes name="mxgraph.electrical.`)) throw new Error(`${g}: unexpected content`);
  sets.push(xml);
}
const header = `/**
 * Electrical stencils from draw.io (https://github.com/jgraph/drawio), Apache License 2.0.
 * Copyright (c) 2006-2025, JGraph Holdings Ltd / draw.io AG.
 *
 * Generated by scripts/gen-electrical-stencils.mjs; regenerate rather than editing by hand.
 */
export const ELECTRICAL_STENCILS: string[] = [
${sets.map((s) => `  ${JSON.stringify(s)},`).join('\n')}
];
`;
fs.mkdirSync(root + 'src/lib/graph/stencils', { recursive: true });
fs.writeFileSync(root + 'src/lib/graph/stencils/electrical.ts', header);
console.log(sets.length, 'stencil sets,', sets.reduce((n, s) => n + (s.match(/<shape /g) ?? []).length, 0), 'shapes');
